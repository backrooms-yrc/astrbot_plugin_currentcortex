def _strip_suffix(text: str) -> str:
    return re.sub(r"(市|省|自治区|特别行政区|地区|盟|自治州)$", "", text.strip())


def lookup_city(query: str) -> Optional[Tuple[float, float, str]]:
    """离线查询城市中心坐标；支持带/不带“市/省/自治区”等后缀。"""
    if not query:
        return None
    text = str(query).strip()
    if not text:
        return None
    for candidate in (text, _strip_suffix(text)):
        if candidate in CITY_COORDS:
            return CITY_COORDS[candidate]
    # 区/县/旗/镇/街道交给在线地理编码，避免“朝阳区”误命中“朝阳（辽宁）”
    if re.search(r"(区|县|旗|镇|街道)$", text):
        return None
    # 直辖市/特别行政区 + 区名：优先按整座城市处理（如“北京朝阳”）
    for municipality in ("北京", "上海", "天津", "重庆", "香港", "澳门"):
        if text.startswith(municipality) and municipality in CITY_COORDS:
            return CITY_COORDS[municipality]
    # 兼容“河北省唐山市”“新疆乌鲁木齐”这类组合：优先取更靠后的具体城市
    matches = [
        (len(key), key)
        for key in CITY_COORDS
        if key and key in text
    ]
    if matches:
        matches.sort(key=lambda item: (text.rfind(item[1]), item[0]), reverse=True)
        return CITY_COORDS[matches[0][1]]
    return None
